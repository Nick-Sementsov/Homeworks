def render(rows, mapping, pal, dye_layer=False):
    """Returns (base, overlay) RGBA float images; with dye_layer the 'dye' role
    pixels go to the base (tinted) layer and everything else to the overlay."""
    assert len(rows) == 16, len(rows)
    base = np.zeros((16, 16, 4), np.float32)
    over = np.zeros((16, 16, 4), np.float32)
    for t, row in enumerate(rows):
        assert len(row) == 16, (t, row, len(row))
        for s, ch in enumerate(row):
            if ch == '.':
                continue
            role, i = mapping[ch]
            rgba = (*pal.col(role, i), 1.0)
            if dye_layer and role != 'dye':
                over[t, s] = rgba
            else:
                base[t, s] = rgba
    return base, over
