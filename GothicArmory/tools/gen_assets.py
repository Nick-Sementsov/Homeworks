#!/usr/bin/env python3
"""Generates every model/texture/data file of the mod from the Python
descriptions in tools/gothic.  Run from the project root:

    python3 tools/gen_assets.py [--previews]
"""
import json
import os
import sys

import numpy as np
from PIL import Image

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gothic import armor, content, decorations, icons, palettes, preview  # noqa: E402
from gothic.model import _var_counter  # noqa: E402
from gothic.paint import paint_model  # noqa: E402

MOD = 'gothicarmory'
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RES = os.path.join(ROOT, 'src', 'main', 'resources')
ASSETS = os.path.join(RES, 'assets', MOD)
DATA = os.path.join(RES, 'data', MOD)
JAVA = os.path.join(ROOT, 'src', 'main', 'java', 'com', 'gothicarmory', 'client', 'model', 'GothicLayers.java')


def save_png(img, path):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    arr = (np.clip(img, 0, 1) * 255).round().astype(np.uint8)
    arr[arr[..., 3] == 0] = 0
    Image.fromarray(arr, 'RGBA').save(path, optimize=True)


def save_json(obj, path):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w', encoding='utf-8') as f:
        json.dump(obj, f, ensure_ascii=False, indent=2)
        f.write('\n')


def camel(name):
    parts = name.split('_')
    return parts[0] + ''.join(p.title() for p in parts[1:])


def build_armor():
    out = {}
    for style in content.STYLES:
        m = armor.build(style)
        m.pack()
        layers = paint_model(m, palettes.STYLES[style], lambda c: 1 if c.piece == 'legs' else 0, m.tex_w, m.tex_h)
        save_png(layers[0], os.path.join(ASSETS, 'textures', 'models', 'armor', f'{style}_gothic_layer_1.png'))
        save_png(layers[1], os.path.join(ASSETS, 'textures', 'models', 'armor', f'{style}_gothic_layer_2.png'))
        out[style] = (m, layers)
    return out


def build_decorations():
    out = {}
    for d in decorations.DECORATIONS:
        m = d.build()
        m.pack()
        layers = paint_model(m, palettes.DECORATION, lambda c: 1 if c.piece == 'overlay' else 0, m.tex_w, m.tex_h)
        base = os.path.join(ASSETS, 'textures', 'models', 'armor', d.name)
        if d.dyeable:
            while len(layers) < 2:
                layers.append(np.zeros_like(layers[0]))
            save_png(layers[0], base + '.png')
            save_png(layers[1], base + '_overlay.png')
        else:
            merged = layers[0].copy()
            for extra in layers[1:]:
                a = extra[..., 3:4] > 0
                merged = np.where(a, extra, merged)
            layers = [merged]
            save_png(merged, base + '.png')
        out[d.name] = (d, m, layers)
    return out


def write_java(armors, decos):
    _var_counter[0] = 0
    lines = [
        '// GENERATED by tools/gen_assets.py - edit the Python model descriptions instead.',
        'package com.gothicarmory.client.model;',
        '',
        'import java.util.LinkedHashMap;',
        'import java.util.Map;',
        'import java.util.function.Supplier;',
        '',
        'import net.minecraft.client.model.geom.PartPose;',
        'import net.minecraft.client.model.geom.builders.CubeDeformation;',
        'import net.minecraft.client.model.geom.builders.CubeListBuilder;',
        'import net.minecraft.client.model.geom.builders.LayerDefinition;',
        'import net.minecraft.client.model.geom.builders.MeshDefinition;',
        'import net.minecraft.client.model.geom.builders.PartDefinition;',
        '',
        'public final class GothicLayers {',
        '    /** Armour models keyed by armour type name (shared by all four pieces of a style). */',
        '    public static final Map<String, Supplier<LayerDefinition>> ARMOR = new LinkedHashMap<>();',
        '    /** Decoration models keyed by decoration name. */',
        '    public static final Map<String, Supplier<LayerDefinition>> DECORATIONS = new LinkedHashMap<>();',
        '',
        '    static {',
    ]
    for style in armors:
        lines.append(f'        ARMOR.put("{style}_gothic", GothicLayers::{camel(style + "_gothic")});')
    for name in decos:
        lines.append(f'        DECORATIONS.put("{name}", GothicLayers::{camel(name)});')
    lines += ['    }', '', '    private GothicLayers() {', '    }', '']
    for style, (m, _) in armors.items():
        lines.append(m.java_method(camel(style + '_gothic')))
        lines.append('')
    for name, (_, m, _) in decos.items():
        lines.append(m.java_method(camel(name)))
        lines.append('')
    lines[-1] = '}'
    os.makedirs(os.path.dirname(JAVA), exist_ok=True)
    with open(JAVA, 'w', encoding='utf-8') as f:
        f.write('\n'.join(lines) + '\n')


def write_icons_and_models():
    items = os.path.join(ASSETS, 'textures', 'item')
    models = os.path.join(ASSETS, 'models', 'item')
    for style in content.STYLES:
        pal = palettes.STYLES[style]
        mp = icons.armor_map(style, armor.OPTS[style])
        for piece in content.PIECES:
            iid = content.item_id(style, piece)
            rows = {'helmet': icons.HELMETS[armor.OPTS[style]['helmet']], 'chestplate': icons.CHEST,
                    'leggings': icons.LEGS, 'boots': icons.BOOTS}[piece]
            base, _ = icons.render(rows, mp, pal)
            save_png(base, os.path.join(items, iid + '.png'))
            save_json({'parent': 'minecraft:item/generated', 'textures': {'layer0': f'{MOD}:item/{iid}'}},
                      os.path.join(models, iid + '.json'))
    for d in decorations.DECORATIONS:
        iid = d.name + '_decoration'
        base, over = icons.render(icons.DECO_ICONS[d.name], icons.DECO_MAP, palettes.DECORATION, d.dyeable)
        save_png(base, os.path.join(items, iid + '.png'))
        tex = {'layer0': f'{MOD}:item/{iid}'}
        if d.dyeable:
            save_png(over, os.path.join(items, iid + '_overlay.png'))
            tex['layer1'] = f'{MOD}:item/{iid}_overlay'
        save_json({'parent': 'minecraft:item/generated', 'textures': tex}, os.path.join(models, iid + '.json'))


def write_lang():
    en, ru = {}, {}
    en[f'itemGroup.{MOD}'] = 'Gothic Armory'
    ru[f'itemGroup.{MOD}'] = 'Готическая оружейная'
    for style in content.STYLES:
        for piece in content.PIECES:
            iid = content.item_id(style, piece)
            en[f'item.{MOD}.{iid}'] = content.en_name(style, piece)
            ru[f'item.{MOD}.{iid}'] = content.RU_NAMES[style][piece]
        en[f'{MOD}.style.{style}'] = content.STYLE_DESC[style][0]
        ru[f'{MOD}.style.{style}'] = content.STYLE_DESC[style][1]
        en[f'{MOD}.bonus.{style}'] = content.BONUS[style][0]
        ru[f'{MOD}.bonus.{style}'] = content.BONUS[style][1]
    en[f'{MOD}.set_bonus'] = 'Full set bonus (%s/4):'
    ru[f'{MOD}.set_bonus'] = 'Бонус полного комплекта (%s/4):'
    en[f'{MOD}.decoration_hint'] = 'Combine with any armor piece in a crafting table'
    ru[f'{MOD}.decoration_hint'] = 'Соедините с любым доспехом на верстаке'
    for name, (e, r, _) in content.DECORATIONS.items():
        en[f'item.{MOD}.{name}_decoration'] = e
        ru[f'item.{MOD}.{name}_decoration'] = r
    save_json(en, os.path.join(ASSETS, 'lang', 'en_us.json'))
    save_json(ru, os.path.join(ASSETS, 'lang', 'ru_ru.json'))


def write_recipes():
    rec = os.path.join(DATA, 'recipes')
    for style in content.STYLES:
        pattern, key = content.STYLE_RECIPE[style]
        for piece in content.PIECES:
            base = content.EK_BASE[piece][style] if piece == 'helmet' else content.EK_BASE[piece]
            k = dict(key)
            k['X'] = {'item': base}
            iid = content.item_id(style, piece)
            save_json({'type': 'minecraft:crafting_shaped', 'category': 'equipment', 'pattern': pattern, 'key': k,
                       'result': {'item': f'{MOD}:{iid}', 'count': 1}}, os.path.join(rec, iid + '.json'))
    for name, (_, _, r) in content.DECORATIONS.items():
        iid = name + '_decoration'
        out = {'result': {'item': f'{MOD}:{iid}', 'count': 1}, 'category': 'equipment'}
        if r['type'] == 'shaped':
            out = {'type': 'minecraft:crafting_shaped', 'category': 'equipment', 'pattern': r['pattern'],
                   'key': r['key'], 'result': out['result']}
        else:
            out = {'type': 'minecraft:crafting_shapeless', 'category': 'equipment',
                   'ingredients': r['ingredients'], 'result': out['result']}
        save_json(out, os.path.join(rec, iid + '.json'))


def write_previews(armors, decos):
    docs = os.path.join(ROOT, 'docs')
    os.makedirs(docs, exist_ok=True)
    imgs = []
    for style, (m, layers) in armors.items():
        imgs.append(preview.render_armor(m, layers, yaw=0.45, scale=11, size=(300, 420)))
    for style, (m, layers) in armors.items():
        imgs.append(preview.render_armor(m, layers, yaw=2.7, scale=11, size=(300, 420), pose=preview.WALK))
    preview.sheet(imgs, 5, os.path.join(docs, 'armor_styles.png'))

    bm, bl = armors['blackened']
    gm, gl = armors['gilded']
    imgs = []
    for name, (d, m, layers) in decos.items():
        lay = [l.copy() for l in layers]
        if d.dyeable:
            col = np.array([(d.dye >> 16) & 255, (d.dye >> 8) & 255, d.dye & 255], np.float32) / 255
            lay[0][..., :3] *= col
        base_m, base_l = (gm, gl) if d.name in ('raven_wings', 'thorn_crown', 'gothic_cape') else (bm, bl)
        if d.slot == 'HELMET':
            imgs.append(preview.render_armor(base_m, base_l, yaw=0.7, scale=15, size=(300, 340),
                                             extra=[(m, lay)], center=(0, -7, 0)))
        else:
            yaw = 2.5 if d.name == 'gothic_cape' else 0.5
            imgs.append(preview.render_armor(base_m, base_l, yaw=yaw, scale=8.5, size=(300, 340),
                                             extra=[(m, lay)], center=(0, 8, 0)))
    preview.sheet(imgs, 4, os.path.join(docs, 'decorations.png'))

    # item icon sheet
    cells = []
    for style in content.STYLES:
        for piece in content.PIECES:
            cells.append(os.path.join(ASSETS, 'textures', 'item', content.item_id(style, piece) + '.png'))
    for d in decorations.DECORATIONS:
        cells.append(os.path.join(ASSETS, 'textures', 'item', d.name + '_decoration.png'))
    scale, cols = 6, 8
    rows = (len(cells) + cols - 1) // cols
    sheet = Image.new('RGBA', (cols * 16 * scale + (cols + 1) * 8, rows * 16 * scale + (rows + 1) * 8), (43, 46, 54, 255))
    for i, p in enumerate(cells):
        im = Image.open(p).convert('RGBA')
        ov = p.replace('.png', '_overlay.png')
        if os.path.exists(ov):
            name = os.path.basename(p)[:-len('_decoration.png')]
            dye = next(d.dye for d in decorations.DECORATIONS if d.name == name)
            arr = np.array(im).astype(np.float32)
            arr[..., :3] *= np.array([(dye >> 16) & 255, (dye >> 8) & 255, dye & 255], np.float32) / 255
            im = Image.fromarray(arr.astype(np.uint8), 'RGBA')
            im.alpha_composite(Image.open(ov).convert('RGBA'))
        im = im.resize((16 * scale, 16 * scale), Image.NEAREST)
        y, x = divmod(i, cols)
        sheet.alpha_composite(im, (8 + x * (16 * scale + 8), 8 + y * (16 * scale + 8)))
    sheet.convert('RGB').save(os.path.join(docs, 'items.png'))


def main():
    armors = build_armor()
    decos = build_decorations()
    write_java(armors, decos)
    write_icons_and_models()
    write_lang()
    write_recipes()
    if '--previews' in sys.argv:
        write_previews(armors, decos)
    print(f'generated {len(armors)} armour styles, {len(decos)} decorations')


if __name__ == '__main__':
    main()
