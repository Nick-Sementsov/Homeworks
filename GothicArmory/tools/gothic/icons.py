def armor_map(style, opts):
    lacquer = opts['lacquer']
    tr = opts['trim']
    m = {
        'O': ('plate', 0), 'D': ('plate', 1), 'M': ('plate', 2), 'L': ('plate', 3), 'H': ('plate', 4),
        'E': (tr, 1), 'V': ('void', 0), 'G': ('trim', 2), 'r': ('leather', 1),
        'c': ('cloth', 1), 'C': ('cloth', 2),
        'W': ('glow', 1) if style == 'wraith' else ('void', 0),
        'P': ('accent', 2) if lacquer else ('plate', 2),
        'p': ('accent', 1) if lacquer else ('plate', 1),
        'Q': ('accent', 3) if lacquer else ('plate', 3),
    }
    return m


